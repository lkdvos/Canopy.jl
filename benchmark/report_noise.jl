# Noise-floor / A-B comparison report for two saved `SUITE` result files.
#
#   julia --project=benchmark benchmark/report_noise.jl \
#       benchmark/baselines/noise1_<sha>_t1.json \
#       benchmark/baselines/noise2_<sha>_t1.json \
#       [--label noise_floor] [--tolerance 0.05]
#
# Writes `benchmark/reports/<label>.md` and prints the per-group summary.
#
# WHAT THE NOISE FLOOR IS FOR
# ---------------------------
# Run the harness twice over *identical* code (phase 0 touches nothing under
# `src/`, which is exactly what makes this possible) and `judge` run 2 against
# run 1. Every non-zero delta is measurement noise. The **maximum absolute delta
# within a group** is that group's noise floor, and the pass/fail threshold for
# any later phase is
#
#       threshold(group) = max(5%, 2 × noise_floor(group))
#
# A phase result inside its group's threshold is not a result. Groups differ by
# an order of magnitude here — `evals = 1` groups (`sweep`, `schedule`,
# `convergence`) are far noisier than the `message` group, which BenchmarkTools
# can loop thousands of times per sample — so a single global threshold would be
# simultaneously too strict for one group and too lax for another.
#
# Both runs must load the same `benchmark/params.json` via `loadparams!`, must be
# on the same host with the same thread counts, and should be taken back-to-back.
# See `benchmark/baselines/README.md`.
#
# A measured floor is **not** a property of the code. On a shared workstation a
# co-tenant job at 100% CPU competes for memory bandwidth and LLC, which these
# memory-bound symmetric fixtures feel directly, so the same two runs taken on a
# quiet box will give a much smaller floor. Two consequences: re-measure the floor
# on the machine and under the load you intend to judge on, and treat a flagged key
# in a group the change cannot have touched as evidence that the *comparison* is
# void rather than that the code regressed.

using BenchmarkTools
using Statistics: median          # BenchmarkTools adds the `BenchmarkGroup` methods
using Printf

const REPORT_DIR = joinpath(@__DIR__, "reports")

function parse_args(args)
    files = String[]
    label = "noise_floor"
    tol = 0.05
    i = 1
    while i <= length(args)
        a = args[i]
        if a == "--label"
            label = args[i + 1]; i += 2
        elseif a == "--tolerance"
            tol = parse(Float64, args[i + 1]); i += 2
        else
            push!(files, a); i += 1
        end
    end
    length(files) == 2 || error("expected two result files, got $(length(files))")
    return files, label, tol
end

# Flatten a `judge` result to `group => Vector{(keypath, ratio)}`, where `ratio`
# is `time(new) / time(old) - 1`.
_at(group, keypath) = foldl((g, k) -> g[k], keypath; init = group)

function group_deltas(jnew, jold)
    out = Dict{String, Vector{Tuple{String, Float64}}}()
    for (group, gnew) in jnew
        haskey(jold, group) || continue
        gold = jold[group]
        rows = Tuple{String, Float64}[]
        for (k, tnew) in BenchmarkTools.leaves(gnew)
            told = try
                _at(gold, k)
            catch
                continue     # key absent from the reference run
            end
            push!(rows, (join(string.(k), " / "), time(tnew) / time(told) - 1))
        end
        sort!(rows; by = r -> -abs(r[2]))
        out[string(group)] = rows
    end
    return out
end

function main(args = ARGS)
    (f1, f2), label, tol = parse_args(args)
    mkpath(REPORT_DIR)

    r1 = BenchmarkTools.load(f1)[1]
    r2 = BenchmarkTools.load(f2)[1]
    m1, m2 = median(r1), median(r2)

    j = judge(m2, m1; time_tolerance = tol)
    deltas = group_deltas(m2, m1)

    io = IOBuffer()
    println(io, "# ", replace(label, '_' => ' ') |> titlecase)
    println(io)
    println(io, "Generated by `benchmark/report_noise.jl`.")
    println(io)
    println(io, "- run 1 (reference): `$(basename(f1))`")
    println(io, "- run 2 (candidate): `$(basename(f2))`")
    println(io, "- host: `$(gethostname())`  ·  CPU: `$(Sys.CPU_NAME)`  ·  julia `$(VERSION)`")
    println(io, "- `judge` time tolerance: $(tol)")
    println(io)
    println(io, "> **This floor includes workstation contention.** It is an upper bound on this")
    println(io, "> host under the load the runs happened to see, not a property of the code.")
    println(io, "> Re-measure on the machine, and under the load, where you intend to judge —")
    println(io, "> see `benchmark/baselines/README.md`.")
    println(io)
    println(io, "Δ is `time(run2) / time(run1) - 1` on the per-key **median**.")
    println(io)
    println(io, "## Per-group summary")
    println(io)
    println(io, "| group | keys | max abs Δ | worst key | median abs Δ | threshold = max(5%, 2×floor) |")
    println(io, "|---|---|---|---|---|---|")
    for g in sort(collect(keys(deltas)))
        rows = deltas[g]
        isempty(rows) && continue
        worst = first(rows)
        floor_ = abs(worst[2])
        @printf(
            io, "| `%s` | %d | **%+.1f%%** | `%s` | %.1f%% | **%.0f%%** |\n",
            g, length(rows), 100 * worst[2], worst[1],
            100 * median(abs(r[2]) for r in rows),
            100 * max(0.05, 2 * floor_),
        )
    end
    println(io)
    println(io, "## `judge` verdicts")
    println(io)
    nreg = length(BenchmarkTools.leaves(regressions(j)))
    nimp = length(BenchmarkTools.leaves(improvements(j)))
    println(io, "- regressions flagged: **$nreg**")
    println(io, "- improvements flagged: **$nimp**")
    println(io)
    if nreg + nimp > 0
        println(io, "Keys flagged (at tolerance $(tol)):")
        println(io)
        for (nm, grp) in (("regression", regressions(j)), ("improvement", improvements(j)))
            for (k, v) in BenchmarkTools.leaves(grp)
                println(io, "- $nm: `$(join(string.(k), " / "))`")
            end
        end
        println(io)
    end
    println(io, "## Worst 5 keys per group")
    println(io)
    for g in sort(collect(keys(deltas)))
        rows = deltas[g]
        isempty(rows) && continue
        println(io, "### `$g`")
        println(io)
        println(io, "| key | Δ |")
        println(io, "|---|---|")
        for (k, d) in Iterators.take(rows, 5)
            @printf(io, "| `%s` | %+.1f%% |\n", k, 100 * d)
        end
        println(io)
    end

    text = String(take!(io))
    path = joinpath(REPORT_DIR, "$label.md")
    write(path, text)
    print(text)
    println("wrote $path")
    return nothing
end

abspath(PROGRAM_FILE) == abspath(@__FILE__) && main()
